import { randomBytes } from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(repoRoot, 'docs', 'verification');

// ─── Options ────────────────────────────────────────────────────────────────

function flag(name: string): boolean {
  return process.argv.includes(`--${name}`);
}

function option(name: string, fallback: number): number {
  const match = process.argv.find((argument) => argument.startsWith(`--${name}=`));
  if (!match) return fallback;
  const value = Number(match.split('=')[1]);
  return Number.isFinite(value) && value > 0 ? value : fallback;
}

const keepUp = flag('keep-up');
const skipLoad = flag('skip-load');
const skipReplicated = flag('skip-replicated');
const SAMPLES = option('samples', 12);
const INTERVAL_MS = option('interval', 5000);
const SETTLE_SECONDS = option('settle', 30);

