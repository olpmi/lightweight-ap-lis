/**
 * Deployment resource profile — container memory and CPU, at idle and under load,
 * measured on the machine that runs it.
 *
 *   pnpm metrics:deployment
 *
 *   --keep-up            leave the stack running afterwards (default: tear down)
 *   --skip-load          idle profile only; skips the benchmark
 *   --skip-replicated    skip the replicated-topology idle profile
 *   --samples=N          samples per window        (default 12)
 *   --interval=MS        gap between samples       (default 5000)
 *   --settle=SECONDS     quiet period before the idle window (default 30)
 *
 * Writes docs/verification/deployment-profile-<stamp>.{md,json}, and pairs with
 * the benchmark-<stamp>.{md,json} written by the run it drives.
 *
 * Why this exists: the manuscript's only resource evidence was "131.75 MB idle,
 * CPU < 0.5%", and neither figure had any provenance in this repository — no
 * command, no host, no timestamp, no commit. Nothing here measured container
 * consumption at all: describeHost() in benchmark.ts records host *capacity*
 * (os.totalmem, os.cpus), never what the stack actually uses. Measuring a
 * container footprint requires the app to run in containers, which neither CI nor
 * the documented local recipe does — both run backend and frontend as host
 * processes. Hence a Docker-based profiler.
 *
 * Why this is deliberately NOT a GitHub workflow, unlike verification.yml: the
 * measurement characterises a host. A shared CI runner would produce a footprint
 * with no deployment meaning, which is worse than no number at all. This is the
 * one metric in the repository that must be generated by a person on a named
 * machine.
 */
