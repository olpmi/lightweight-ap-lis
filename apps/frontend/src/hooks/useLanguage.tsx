type TranslationKey = keyof typeof en;
type Translations = Readonly<Record<TranslationKey, string>>;

interface LanguageContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  direction: 'ltr' | 'rtl';
  languageOptions: readonly LanguageOption[];
  t: (key: keyof Translations) => string;
  tSite: (englishName: string) => string;
  tOrgan: (englishName: string) => string;
  tSpecimenType: (englishName: string) => string;
  tSlideType: (englishName: string) => string;
  tCaseType: (englishName: string) => string;
  tSex: (englishName: string) => string;
  tRole: (englishName: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

const DICTS: Partial<Record<Lang, Translations>> = { en, sw, fr, ar, ur };

function isSupportedLanguage(value: string | null): value is Lang {
  return value !== null && APP_LANGUAGE_CODES.includes(value as Lang);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const stored = (typeof localStorage !== 'undefined' ? localStorage.getItem('ap_lis_lang') : null) as Lang | null;
  const [lang, setLangState] = useState<Lang>(isSupportedLanguage(stored) ? stored : 'en');

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem('ap_lis_lang', l);
  }, []);

  const dict = DICTS[lang] ?? en;
  const direction = LANGUAGE_OPTIONS_BY_CODE[lang]?.direction ?? 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = direction;
  }, [direction, lang]);

  // Memoize the context value so consumers don't re-render on every parent
  // render. All helpers are derived from `dict`, so they only need to change
  // when the language changes.
  const value = useMemo<LanguageContextValue>(() => {
    const t = (key: keyof Translations) => dict[key] as string;
    const tFromMap = (map: Record<string, keyof Translations>) =>
      (name: string) => {
        const key = map[name];
        return key ? (dict[key] as string) : name;
      };
    return {
      lang,
      setLang,
      direction,
      languageOptions: LANGUAGE_OPTIONS,
      t,
      tSite: tFromMap(SITE_KEY_MAP),
      tOrgan: tFromMap(ORGAN_KEY_MAP),
      tSpecimenType: tFromMap(SPECIMEN_TYPE_KEY_MAP),
      tSlideType: tFromMap(SLIDE_TYPE_KEY_MAP),
      tCaseType: tFromMap(CASE_TYPE_KEY_MAP),
      tSex: tFromMap(SEX_KEY_MAP),
      tRole: tFromMap(ROLE_KEY_MAP),
    };
  }, [dict, direction, lang, setLang]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}
